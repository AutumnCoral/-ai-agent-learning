# Python 变量的基本类型

# 字符串类型：保存文本。
name = "w"

# 整数类型：保存没有小数部分的数字。
age = 12

# 布尔类型：只有 True 或 False 两种值。
is_back = False

# 浮点数类型：保存带小数部分的数字。
score = 32.4

# 字符串也可以调用方法进行处理。
text = "Hello World"

# 同时输出多个变量的值。
print(name, age, is_back, score)

# 使用 type() 查看变量的数据类型。
print(type(name))
print(type(age))

# lower() 将字符串转换为小写，upper() 将字符串转换为大写。
print(text.lower())
print(text.upper())